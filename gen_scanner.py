"""Generate the multi-symbol Pine scanner from a symbol list.

Pine cannot loop over symbols: ``request.security`` needs a *simple string*, so
every symbol costs one hand-written call. Twenty-five of those written by hand
is twenty-five chances to transpose a ticker, and a wrong ticker fails silently
as ``na`` rather than as an error - it would just quietly never signal.

So the source is generated. When the watchlist changes, re-run this instead of
editing Pine.

**Tradability is carried into the output on purpose.** An alert you cannot act
on is noise, and this stack can only reach US equities/ETFs and a handful of
crypto pairs through Alpaca. Indices, CFDs and FX are still watched - the signal
is real - but the table marks them so a signal on SPX is never mistaken for
something you can place.

    python gen_scanner.py                       # writes pine/vtl_multi_scanner.pine
    python gen_scanner.py --tradable-only       # skip anything Alpaca cannot reach
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# (tv_symbol, label, tradable_on_alpaca)
WATCHLIST: list[tuple[str, str, bool]] = [
    ("NASDAQ:AAPL",  "AAPL",  True),
    ("NASDAQ:TSLA",  "TSLA",  True),
    ("NASDAQ:NFLX",  "NFLX",  True),
    ("NASDAQ:NVDA",  "NVDA",  True),
    ("NASDAQ:AMZN",  "AMZN",  True),
    ("NASDAQ:PLTR",  "PLTR",  True),
    ("NASDAQ:META",  "META",  True),
    ("NASDAQ:GOOGL", "GOOGL", True),
    ("NASDAQ:AMD",   "AMD",   True),
    ("AMEX:GLD",     "GLD",   True),
    ("AMEX:VOO",     "VOO",   True),
    ("BITSTAMP:BTCUSD", "BTC", True),   # Alpaca: BTC/USD, long only
    ("BITSTAMP:ETHUSD", "ETH", True),   # Alpaca: ETH/USD, long only
    ("SPCFD:SPX",    "SPX",   False),
    ("TVC:NDQ",      "NDQ",   False),
    ("TVC:DJI",      "DJI",   False),
    ("CBOE:VIX",     "VIX",   False),
    ("TVC:DXY",      "DXY",   False),
    ("TVC:USOIL",    "USOIL", False),
    ("TVC:GOLD",     "GOLD",  False),
    ("TVC:SILVER",   "SILVR", False),
    ("FX:EURUSD",    "EURUSD", False),
    ("FX:GBPUSD",    "GBPUSD", False),
    ("FX:USDJPY",    "USDJPY", False),
]

# Pine allows 40 request.* calls. One is spent on EURUSD for the FX conversion.
MAX_SECURITY_CALLS = 39

HEADER = '''//@version=6
// VTL multi-symbol scanner - ONE alert for the whole watchlist.
//
// GENERATED by gen_scanner.py - do not hand-edit; re-run the generator.
//
// Why it exists: TradingView alerts are per-symbol and the VTL strategy only
// sees the chart it is attached to. Covering a {n}-symbol watchlist that way
// means {n} alerts, {n} dialogs and {n} slots against the account alert limit.
// This watches them all from one chart, so ONE alert covers the lot.
//
// It is an indicator, so there is no strategy.* position state - the book is
// tracked explicitly in arrays below. That makes the P&L a clean mark against
// the tracked entry. It mirrors the strategy's logic; it is not its backtest.
//
// Symbols marked "-" in the TRADE column cannot be reached through Alpaca
// (indices, CFDs, FX). Their signals are still computed, because they are real,
// but a signal you cannot act on must never look like one you can.
//
// P&L is reported three ways - percent, USD and EUR - matching
// vtl_session_strategy.pine. EUR degrades to "n/a", never to zero.
indicator("VTL multi-symbol scanner", overlay = false, max_bars_back = 300)

fastLen  = input.int(20,  "Fast SMA", minval = 2)
slowLen  = input.int(50,  "Slow SMA", minval = 3)
rsiLen   = input.int(14,  "RSI length", minval = 2)
rsiMax   = input.float(70, "RSI overbought")
atrLen   = input.int(14,  "ATR length", minval = 2)
stopMult = input.float(2.0, "Stop x ATR")
riskPct  = input.float(0.01, "Risk per trade", step = 0.005)
acctEq   = input.float(100000, "Equity per symbol")
showAll  = input.bool(true, "Show untradable symbols too")

// USD -> EUR, resolved once at global scope and reused everywhere below.
eurusd = request.security("FX_IDC:EURUSD", "D", close, ignore_invalid_symbol = true)
usdEur = na(eurusd) or eurusd <= 0 ? na : 1.0 / eurusd

fmtSigned(v, pre) =>
    (v >= 0 ? "+" : "-") + pre + str.tostring(math.abs(v), "#,###.##")

money(usd, pct) =>
    base = fmtSigned(pct, "") + "% | " + fmtSigned(usd, "$")
    na(usdEur) ? base + " | EUR n/a" : base + " | " + fmtSigned(usd * usdEur, "EUR ")

// Evaluated in each symbol's own context so nothing repaints across symbols.
probe() =>
    f = ta.sma(close, fastLen)
    s = ta.sma(close, slowLen)
    r = ta.rsi(close, rsiLen)
    a = ta.atr(atrLen)
    [close, f, s, r, a, ta.crossover(f, s), ta.crossunder(f, s)]
'''

STEP = '''
var float[] entryPx = array.new_float({n}, na)
var float[] qtyArr  = array.new_float({n}, 0.0)
var float[] stopArr = array.new_float({n}, na)

// One symbol: open it, close it, or leave it. Alerts on any transition.
step(i, sym, tradable, px, fastV, slowV, rsiV, atrV, xover, xunder) =>
    stopLv = array.get(stopArr, i)
    out    = ""

    if na(array.get(entryPx, i)) and xover and rsiV < rsiMax and atrV > 0
        rps = stopMult * atrV
        q   = rps > 0 ? math.floor(acctEq * riskPct / rps) : 0
        if q > 0
            array.set(entryPx, i, px)
            array.set(qtyArr,  i, q)
            array.set(stopArr, i, px - rps)
            alert((tradable ? "PAPER BUY " : "SIGNAL (untradable) ") + sym +
                  " | entry ~" + str.tostring(px, "#.####") +
                  " | STOP " + str.tostring(px - rps, "#.####") +
                  " | qty " + str.tostring(q, "#"),
                  alert.freq_once_per_bar_close)

    if not na(array.get(entryPx, i))
        ep  = array.get(entryPx, i)
        q   = array.get(qtyArr, i)
        pnl = (px - ep) * q
        pct = ep > 0 ? (px - ep) / ep * 100 : 0.0
        // Stop first: if the stop and the cross-down land on the same bar, the
        // stop is what would actually have filled.
        hitStop = not na(stopLv) and px <= stopLv
        if hitStop or xunder
            alert((pnl >= 0 ? "PROFIT" : "LOSS") + " " + sym + " CLOSED" +
                  " | " + money(pnl, pct) +
                  " | entry " + str.tostring(ep, "#.####") +
                  " -> exit " + str.tostring(px, "#.####") +
                  " | reason: " + (hitStop ? "STOP" : "SMA cross down"),
                  alert.freq_once_per_bar_close)
            array.set(entryPx, i, na)
            array.set(qtyArr,  i, 0.0)
            array.set(stopArr, i, na)
            out := "closed " + money(pnl, pct)
        else
            array.set(stopArr, i, math.max(nz(stopLv, px - stopMult * atrV),
                                           px - stopMult * atrV))
            out := "OPEN " + money(pnl, pct)
    else
        out := fastV > slowV ? (rsiV < rsiMax ? "armed" : "RSI blocked") : "flat"
    out
'''

TABLE_HEAD = '''
var table t = table.new(position.top_right, 4, {rows}, border_width = 1)
paint(row, sym, tradable, px, txt) =>
    col = str.startswith(txt, "OPEN +") or str.startswith(txt, "closed +") ? color.lime :
          str.startswith(txt, "OPEN -") or str.startswith(txt, "closed -") ? color.red :
          txt == "armed" ? color.yellow : color.silver
    table.cell(t, 0, row, sym, text_color = tradable ? color.white : color.gray)
    table.cell(t, 1, row, tradable ? "Y" : "-",
         text_color = tradable ? color.teal : color.gray)
    table.cell(t, 2, row, str.tostring(px, "#.####"), text_color = color.silver)
    table.cell(t, 3, row, txt, text_color = col)

if barstate.islast
    table.cell(t, 0, 0, "SCANNER", bgcolor = color.new(color.gray, 60), text_color = color.white)
    table.cell(t, 1, 0, "TRADE",   bgcolor = color.new(color.gray, 60), text_color = color.white)
    table.cell(t, 2, 0, "last",    bgcolor = color.new(color.gray, 60), text_color = color.white)
    table.cell(t, 3, 0, "state / P&L", bgcolor = color.new(color.gray, 60), text_color = color.white)
'''


def generate(rows: list[tuple[str, str, bool]]) -> str:
    """Emit the full Pine source for *rows*."""
    n = len(rows)
    out = [HEADER.format(n=n)]

    # request.security is one call per symbol - unavoidable, see module docstring.
    out.append("\n// -- one request.security per symbol; Pine cannot loop these --\n")
    for i, (tv, label, _) in enumerate(rows):
        out.append(f'[c{i}, f{i}, s{i}, r{i}, a{i}, xo{i}, xu{i}] = '
                   f'request.security("{tv}", "D", probe(), ignore_invalid_symbol = true)\n')

    out.append(STEP.format(n=n))

    out.append("\n")
    for i, (_, label, tradable) in enumerate(rows):
        out.append(f'st{i} = step({i}, "{label}", {str(tradable).lower()}, '
                   f'c{i}, f{i}, s{i}, r{i}, a{i}, xo{i}, xu{i})\n')

    out.append(TABLE_HEAD.format(rows=n + 1))
    # Tradable rows paint unconditionally; watch-only rows sit behind showAll so
    # the table can be collapsed to just what is actionable.
    for row, (i, (_, label, tradable)) in enumerate(enumerate(rows), start=1):
        if tradable:
            out.append(f'    paint({row}, "{label}", true, c{i}, st{i})\n')
        else:
            out.append(f'    if showAll\n'
                       f'        paint({row}, "{label}", false, c{i}, st{i})\n')
    return "".join(out)


def main() -> int:
    """Write the scanner, refusing to exceed Pine's request.security budget."""
    ap = argparse.ArgumentParser(description="Generate the Pine scanner")
    ap.add_argument("--tradable-only", action="store_true")
    ap.add_argument("--out", default="pine/vtl_multi_scanner.pine")
    args = ap.parse_args()

    rows = [r for r in WATCHLIST if r[2]] if args.tradable_only else list(WATCHLIST)
    if len(rows) > MAX_SECURITY_CALLS:
        print(f"{len(rows)} symbols exceeds Pine's budget of {MAX_SECURITY_CALLS} "
              f"request.security calls (one is spent on EURUSD). Trim the list or "
              f"use --tradable-only.", file=sys.stderr)
        return 1

    path = Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate(rows), encoding="utf-8", newline="\n")
    tradable = sum(1 for r in rows if r[2])
    print(f"wrote {path}  -  {len(rows)} symbols, {tradable} tradable on Alpaca, "
          f"{len(rows) - tradable} watch-only")
    print(f"request.security calls: {len(rows) + 1} of {MAX_SECURITY_CALLS + 1}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
